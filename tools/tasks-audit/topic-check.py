def bank_for(grade, topic):
    if topic == 'safety':
        return SAFETY
    m = re.match(r'^lesson:(\d+)$', str(topic))
    if m:
        n = int(m.group(1))
        return G7_LESSON.get(n) if grade == 7 else None
    m = re.match(r'^p(\d+)$', str(topic))
    if m:
        n = int(m.group(1))
        return (G8_SECTION.get(n) if grade == 8 else G9_LESSON.get(n) if grade == 9 else None)
    m = re.match(r'^lab(\d+)$', str(topic))
    if m:
        n = int(m.group(1))
        return (G7_LAB.get(n) if grade == 7 else G8_LAB.get(n) if grade == 8 else G9_LAB.get(n) if grade == 9 else None)
    if grade == 7 and topic in G7_POOL:
        return G7_POOL[topic]
    return None

def bank_class(grade, topic):
    if topic == 'safety':
        return 'safety'
    if re.match(r'^lesson:\d+$', str(topic)):
        return 'g7lesson'
    if re.match(r'^p\d+$', str(topic)):
        return 'sections'
    if re.match(r'^lab\d+$', str(topic)):
        return 'labs'
    return 'named'

def comparison_table(grade, cls):
    if cls == 'g7lesson':
        return {k: v for k, v in G7_LESSON.items() if k != 1}
    if cls == 'sections':
        return G8_SECTION if grade == 8 else G9_LESSON
    if cls == 'labs':
        return G7_LAB if grade == 7 else G8_LAB if grade == 8 else G9_LAB
    if cls == 'named':
        return G7_POOL
    return {}

def text_of(t):
    parts = []
    if isinstance(t.get('question'), dict):
        parts.append(t['question'].get('ru', ''))
    v = t.get('options')
    if isinstance(v, dict):
        o = v.get('ru', [])
        if isinstance(o, list):
            parts.append(' '.join(o))
    ex = t.get('explanation')
    if isinstance(ex, dict):
        parts.append(ex.get('ru', ''))
    ans = t.get('answer')
    if isinstance(ans, dict):
        a = ans.get('ru')
        if isinstance(a, str):
            parts.append(a)
    return norm(' '.join(parts))

def _hit(text, key):
    k = norm(key)
    # фраза: все слова должны дать совпадение по основе — устойчиво к падежам каждого слова
    if ' ' in k:
        return all(_hit(text, w) for w in k.split())
    if not re.search(r'[а-яё]', k):
        # чисто латинский ключ (sin, n, g, utc): границы слова, чтобы 'g' не матчилось внутри 'log'
        return re.search(r'(?<![a-z0-9])' + re.escape(k) + r'(?![a-z0-9])', text) is not None
    # русское слово: сравниваем по основе из 4 букв — устойчиво к любому склонению/спряжению
    if len(k) > 4:
        k = k[:4]
    return k in text

def score(text, keys):
    if not keys:
        return 0
    s = 0
    for k in keys:
        if _hit(text, k):
            s += 1
    return s

