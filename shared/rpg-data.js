/* ---------------- РЕКОМЕНДУЕМАЯ МИССИЯ ---------------- */
function rpgRecommendedMission(levelId) {
    const numeric = typeof levelId === "number"
        ? levelId
        : String(levelId).split("").reduce((sum, ch) => sum + ch.charCodeAt(0), 0);
    if (numeric % 7 === 0) return "boss";
    if (numeric % 5 === 0) return "blitz";
    if (numeric % 4 === 0) return "survival";
    if (numeric % 3 === 0) return "harvest";
    return "defense";
}

/* ---------------- XP / УРОВНИ ---------------- */
function rpgXpForLevel(level) {
    return Math.round(120 * Math.pow(Math.max(1, level), 1.32));
}
function rpgRankForLevel(level) {
    let rank = RANKS[0];
    RANKS.forEach(r => { if (level >= r.min) rank = r; });
    return rank;
}


