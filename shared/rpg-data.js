/** Проверка полноты казахской локализации (для консоли). */
function rpgKkCoverage() {
    const missing = [];
    Object.keys(UI.ru).forEach(k => { if (!UI.kk[k]) missing.push("ui:" + k); });
    MISSIONS_LIST.forEach(m => {
        ["name", "tag", "desc", "objective"].forEach(f => {
            if (!m[f] || !m[f].kk) missing.push("mission:" + m.id + ":" + f);
        });
        if (m.rules && m.rules.kk && m.rules.kk.length !== m.rules.ru.length) missing.push("mission:" + m.id + ":rules");
    });
    PERKS.forEach(p => { if (!p.name.kk || !p.desc.kk) missing.push("perk:" + p.id); });
    ARTIFACTS.forEach(a => { if (!a.name.kk || !a.desc.kk) missing.push("artifact:" + a.id); });
    TITLES.forEach(t => { if (!t.name.kk) missing.push("title:" + t.id); });
    RANKS.forEach((r, i) => { if (!r.name.kk) missing.push("rank:" + i); });
    Object.keys(TIER_INFO).forEach(t => { if (!TIER_INFO[t].label.kk) missing.push("tier:" + t); });
    ACHIEVEMENTS.forEach(a => { if (!a.name.kk || (!a.secret && !a.desc.kk)) missing.push("ach:" + a.id); });
    QUEST_POOL.forEach(q => { if (!q.name.kk || !q.desc.kk) missing.push("quest:" + q.id); });
    return missing;
}
