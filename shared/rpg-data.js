(function applyKazakhPack() {
    const put = (target, field, value) => {
        if (!target || !target[field] || typeof target[field] !== "object" || value === undefined) return;
        target[field].kk = value;
    };
    // Миссии: имя, категория, описание, правила, цель.
    MISSIONS_LIST.forEach(m => {
        const k = RPG_KK.missions[m.id];
        if (!k) return;
        put(m, "name", k.name);
        put(m, "tag", k.tag);
        put(m, "desc", k.desc);
        put(m, "objective", k.objective);
        if (Array.isArray(m.rules) && Array.isArray(k.rules)) {
            m.rules = { ru: m.rules.ru, en: m.rules.en, kk: k.rules };
        }
    });
    PERKS.forEach(p => {
        const k = RPG_KK.perks[p.id];
        if (!k) return;
        put(p, "name", k[0]);
        put(p, "desc", k[1]);
    });
    ARTIFACTS.forEach(a => {
        const k = RPG_KK.artifacts[a.id];
        if (!k) return;
        put(a, "name", k[0]);
        put(a, "desc", k[1]);
    });
    TITLES.forEach((t, i) => put(t, "name", RPG_KK.titles[i]));
    RANKS.forEach((r, i) => put(r, "name", RPG_KK.ranks[i]));
    Object.keys(TIER_INFO).forEach(tier => {
        const label = RPG_KK.tiers[tier];
        if (label) TIER_INFO[tier].label.kk = label;
    });
    ACHIEVEMENTS.forEach(a => {
        const k = RPG_KK.achievements[a.id];
        if (!k) return;
        put(a, "name", k[0]);
        put(a, "desc", k[1]);
    });
    QUEST_POOL.forEach(q => {
        const k = RPG_KK.quests[q.id];
        if (!k) return;
        put(q, "name", k[0]);
        put(q, "desc", k[1]);
    });
})();

